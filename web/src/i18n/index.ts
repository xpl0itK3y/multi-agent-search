const stored = (typeof localStorage !== "undefined" && localStorage.getItem("locale")) as Locale | null;

// Russian has three plural forms ("1 пункт | 3 пункта | 5 пунктов"); vue-i18n's
// default rule only knows singular/plural, which en and es use.
export function ruPluralRule(choice: number, choicesLength: number): number {
  const n = Math.abs(choice);
  if (choicesLength < 3) return n === 1 ? 0 : 1;
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return 0;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return 1;
  return 2;
}

export const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: stored && ["ru", "en", "es"].includes(stored) ? stored : "ru",
  fallbackLocale: "en",
  pluralRules: { ru: ruPluralRule },
  messages: { ru, en, es },
});
